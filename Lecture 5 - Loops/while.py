# loops --- while / for loop
# used to repeat instruction

# while -- reserved keyword
count = 1  # iterator
while count<=5:   # iteration
  print("hello", count)
  count += 1
print(count)


# print num from 1-10
num = 1
while num<=10:
  print(num)
  num+=1
print("loop ended")



# print num from 10-1
num = 10
while num>=1:
  print(num)
  num-=1
print("loop ended")





